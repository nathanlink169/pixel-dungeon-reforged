public class Bolas extends MissileWeapon {
	
	{
		image = ItemSpriteSheet.BOLAS;
		hitSound = Assets.Sounds.HIT;
		hitSoundPitch = 1f;
		
		tier = 3;
		baseUses = 5;

		damageType = DamageType.of(DamageType.BLUDGEONING);
	}
	
	@Override
	public int max(int lvl) {
		return  3 * tier +                      //9 base, down from 15
				(tier == 1 ? 2*lvl : tier*lvl); //scaling unchanged
	}
	@Override
	public void onHit(AttackContext context, int finalDamage) {
		Buff.prolong( context.defender, Cripple.class, Cripple.DURATION );
		super.onHit( context, finalDamage );
	}
}
